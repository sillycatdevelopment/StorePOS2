namespace StorePos.Core.Models;

public class Delivery
{
    public int Id { get; set; }
    public int SupplierId { get; set; }
    public Supplier? Supplier { get; set; }
    public DateTime ReceivedAt { get; set; }
    public string? InvoiceNumber { get; set; }
    public string? Notes { get; set; }
    public long TotalCostCents { get; set; }
    public int? StockingListId { get; set; }
    public StockingList? StockingList { get; set; }
    public int? UserId { get; set; }
    public User? User { get; set; }
    public List<DeliveryItem> Items { get; set; } = new();
}

public class DeliveryItem
{
    public int Id { get; set; }
    public int DeliveryId { get; set; }
    public Delivery? Delivery { get; set; }
    public int ProductId { get; set; }
    public Product? Product { get; set; }
    public int OwnerId { get; set; }
    public Owner? Owner { get; set; }
    public long Quantity { get; set; }
    public long UnitCostCents { get; set; }
    public long LineCostCents { get; set; }
}

public class StockingList
{
    public int Id { get; set; }
    public string Name { get; set; } = "";
    public StockingListStatus Status { get; set; } = StockingListStatus.Draft;
    public bool IsAutoGenerated { get; set; }
    public StockingGroupBy GroupBy { get; set; }
    public string? Notes { get; set; }
    public DateTime CreatedAt { get; set; }
    public int? CreatedByUserId { get; set; }
    public User? CreatedByUser { get; set; }
    public DateTime? PurchasedAt { get; set; }
    public DateTime? ReceivedAt { get; set; }
    public List<StockingListItem> Items { get; set; } = new();
}

public class StockingListItem
{
    public int Id { get; set; }
    public int StockingListId { get; set; }
    public StockingList? StockingList { get; set; }
    /// <summary>Null for a customer-requested item that is not a product yet.</summary>
    public int? ProductId { get; set; }
    public Product? Product { get; set; }
    public int? CustomerRequestId { get; set; }
    public CustomerRequest? CustomerRequest { get; set; }
    public string Description { get; set; } = "";
    public int? SupplierId { get; set; }
    public Supplier? Supplier { get; set; }
    public int? OwnerId { get; set; }
    public Owner? Owner { get; set; }
    public long CurrentStock { get; set; }
    public double AvgDailySales { get; set; }
    public int? DaysToNextDelivery { get; set; }
    public long SuggestedQty { get; set; }
    /// <summary>Quantity the user actually wants (editable override).</summary>
    public long Quantity { get; set; }
    public long EstimatedUnitCostCents { get; set; }
    public string? Reason { get; set; }
}

/// <summary>A product customers asked for that the store did not have. Aggregated by name.</summary>
public class CustomerRequest
{
    public int Id { get; set; }
    public string ProductName { get; set; } = "";
    public string NormalizedName { get; set; } = "";
    public string? Barcode { get; set; }
    public int? CategoryId { get; set; }
    public Category? Category { get; set; }
    /// <summary>Set when the request matches (or later becomes) a catalog product.</summary>
    public int? ProductId { get; set; }
    public Product? Product { get; set; }
    public RequestStatus Status { get; set; } = RequestStatus.Pending;
    public int RequestCount { get; set; }
    public long TotalQuantity { get; set; }
    public DateTime FirstRequestedAt { get; set; }
    public DateTime LastRequestedAt { get; set; }
    public string? Notes { get; set; }
    public List<CustomerRequestEvent> Events { get; set; } = new();
}

public class CustomerRequestEvent
{
    public int Id { get; set; }
    public int CustomerRequestId { get; set; }
    public CustomerRequest? CustomerRequest { get; set; }
    public DateTime RequestedAt { get; set; }
    public long Quantity { get; set; }
    public string? Notes { get; set; }
    public int? UserId { get; set; }
}
